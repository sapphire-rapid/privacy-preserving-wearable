"""Step 6: export the final wrist LR@26 Hz as drop-in headers  (ml/fall-detection/src/export_final.py, fixed).

Fixes w.r.t. the reference exporter
  * fall_model.h carries every rate-dependent macro (SAMPLE_RATE_HZ, WIN/STRIDE/CONFIRM, TILT_PRE/POST/FALLBACK, POST_STD, ...)
    and the matching LSM6DSXX ODR selection (imu.c derives IMU_ODR_ENUM from SAMPLE_RATE_HZ == 26).
  * the stillness thresholds are emitted as the macros FALL_STILL_STD_THR / FALL_STILL_MEAN_TOL: firmware fall_features.h
    only uses those macros (the reference `static const STILL_STD_THR` was dead code, so a tuned std would have been ignored).
  * every float literal has a decimal point before the exponent / 'f' suffix (1.0e-05f, 3.0f), never 1e-05f or 3f.
  * test_windows.h uses REAL windows / stillness segments from the TRAIN pool (not synthetic noise), with expected features,
    probabilities and decisions computed from the float32-rounded inputs actually stored in the header.
Usage: .venv/bin/python -I src/export_final.py [--op spec|ext|trig] [--thr X --std Y]
Writes only to ml/fall-detection-wrist/include/ (firmware/fall_imu/include is NOT touched).
"""
import os
import sys
import json
import pickle
import argparse
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import features as F

ROOT = os.path.dirname(HERE)
INC = os.path.join(ROOT, "include")
RES = os.path.join(ROOT, "results")
CACHE = os.path.join(ROOT, "cache")
os.makedirs(INC, exist_ok=True)
C = F.CFG26


def flt(x):
    """float32 literal in positional notation: shortest string that round-trips float32, always with a decimal point
    before the f suffix (3.0f, 0.671f, -0.0000202726624f) -- never 3f or 1e-05f."""
    s = np.format_float_positional(np.float32(x), unique=True, trim="0")
    if "." not in s:
        s += ".0"
    if s.endswith("."):
        s += "0"
    return s + "f"


def arr(name, vals):
    return "static const float " + name + "[] = {\n    " + ", ".join(flt(v) for v in vals) + "\n};"


def lr_prob(feat, m):
    xs = (np.asarray(feat, dtype=np.float64) - m["mean"]) / m["scale"]
    return float(1.0 / (1.0 + np.exp(-(xs @ m["coef"] + m["intercept"]))))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--op", default="trig", choices=["spec", "ext", "trig"])
    ap.add_argument("--thr", type=float); ap.add_argument("--std", type=float)
    a = ap.parse_args()
    fm = json.load(open(os.path.join(RES, "final_model.json")))
    m = dict(mean=np.array(fm["mean"]), scale=np.array(fm["scale"]), coef=np.array(fm["coef"]), intercept=fm["intercept"])
    op = fm["operating_points"][a.op]
    thr = a.thr if a.thr is not None else op["thr"]
    std = a.std if a.std is not None else op["std"]
    tol = fm["mean_tol"]
    prov = a.thr is None            # until the confirm-stage question in REPORT.md is settled, every export is provisional

    # ---------------------------------------------------------------- fall_model.h
    h = ["#ifndef FALL_MODEL_H", "#define FALL_MODEL_H", ""]
    h.append("/* Wrist fall model: logistic regression on the 9 features of features_v2.py, retrained on WEDA-FALL + SmartFallMM (Meta_wrist),")
    h.append(" * 26 Hz.  Generated by ml/fall-detection-wrist/src/export_final.py -- do not edit.")
    h.append(f" * Operating point: mode '{a.op}', prob threshold {thr}, stillness std {std}, mean tolerance {tol}.")
    if prov:
        h.append(" * PROVISIONAL: the >=95 % fall-recall target is NOT reachable with the specified stillness-confirm rule on wrist data")
        h.append(" * (see ml/fall-detection-wrist/results/REPORT.md). mode 'trig' = threshold tuned WITHOUT the confirm stage (>=95 % trigger-only")
        h.append(" * recall); the stillness parameters below are NOT validated for wrist data. Not for deployment until that is decided.")
    h.append(" * SmartFallMM (c) SmartFall Group, Texas State University (credit required); WEDA-FALL (Marques et al.); weights only, no raw data. */")
    h.append("")
    h.append("#define N_FEATURES 9")
    h.append("/* Feature order (features_v2.py):")
    for i, fn in enumerate(F.FEATURE_NAMES):
        h.append(f" *  {i}: {fn}")
    h.append(" */")
    h.append("")
    h.append(arr("FALL_MEAN", m["mean"]))
    h.append(arr("FALL_SCALE", m["scale"]))
    h.append(arr("FALL_COEF", m["coef"]))
    h.append(f"static const float FALL_INTERCEPT = {flt(m['intercept'])};")
    h.append(f"static const float FALL_PROB_THR = {flt(thr)};")
    h.append("/* stillness: macros are what fall_features.h reads (its #ifndef defaults are 0.05f / 0.2f) */")
    h.append(f"#define FALL_STILL_STD_THR   {flt(std)}")
    h.append(f"#define FALL_STILL_MEAN_TOL  {flt(tol)}")
    h.append(f"static const float STILL_STD_THR = {flt(std)};")
    h.append(f"static const float STILL_MEAN_TOL = {flt(tol)};")
    h.append(f"#define CONFIRM_SAMPLES {C.confirm}")
    h.append(f"#define WIN_SAMPLES {C.win}")
    h.append(f"#define STRIDE_SAMPLES {C.stride}")
    h.append(f"#define SAMPLE_RATE_HZ {C.fs}")
    h.append("")
    h.append("/* ---- rate-dependent constants (samples at SAMPLE_RATE_HZ) ---- */")
    h.append(f"#define TILT_PRE_SAMPLES       {C.tilt_pre}   /* tilt 'before' mean: samples before the peak (0.5 s) */")
    h.append(f"#define TILT_POST_SAMPLES      {C.tilt_post}   /* tilt 'after' mean: last samples of the window (0.5 s) */")
    h.append(f"#define TILT_FALLBACK_SAMPLES  {C.tilt_fallback}    /* tilt 'before' = first N when peak < PRE (10 @52 Hz scaled) */")
    h.append(f"#define POST_STD_SAMPLES       {C.post_std}   /* std_mag_post: last 1 s of the window */")
    h.append("/* short aliases (spec names) */")
    h.append("#define TILT_PRE       TILT_PRE_SAMPLES")
    h.append("#define TILT_POST      TILT_POST_SAMPLES")
    h.append("#define TILT_FALLBACK  TILT_FALLBACK_SAMPLES")
    h.append("#define POST_STD       POST_STD_SAMPLES")
    h.append("")
    h.append("/* ---- IMU ODR for this model ----")
    h.append(" * firmware/fall_imu/imu.c selects LSM6DSXX_DATA_RATE_26HZ from SAMPLE_RATE_HZ == 26 (a header swap is enough);")
    h.append(" * the macros below name that selection explicitly (LSM6DS3TR-C CTRL1_XL ODR_XL[3:0] = 0b0010 = 26 Hz). */")
    h.append("#define MODEL_IMU_ODR_ENUM     LSM6DSXX_DATA_RATE_26HZ")
    h.append("#define MODEL_IMU_ODR_XL_BITS  0x2")
    h.append("")
    h.append("#endif")
    open(os.path.join(INC, "fall_model.h"), "w").write("\n".join(h) + "\n")
    print("wrote fall_model.h", "(PROVISIONAL operating point)" if prov else "")

    # ---------------------------------------------------------------- test_windows.h  (REAL train-pool windows)
    pool = []
    for name in ("weda", "sfmm"):
        pool += pickle.load(open(os.path.join(CACHE, name + ".pkl"), "rb"))
    rng = np.random.default_rng(7)

    def feat_prob(w32):
        f = np.array(F.features_of_window(w32.astype(np.float64), C), dtype=np.float32)
        return f, lr_prob(f.astype(np.float64), m)

    def ok_margin(p):
        return abs(p - thr) > 2e-3 * max(thr, 0.05)

    falls = [r for r in pool if r["is_fall"] and len(r["x26"]) >= C.win]
    adl = [r for r in pool if not r["is_fall"] and len(r["x26"]) >= C.win]
    hard = [r for r in adl if r["ftype"] in ("D02", "D07", "D08", "D05")]      # jog, stumble, jump, collapse into chair
    sel = []
    # 6 falls (alternating datasets), 6 ADL: 2 hard
    def impact_window(r):
        x = r["x26"]
        s, _ = F.fall_label_start(F.mag(x.astype(np.float64)), len(x), C)
        return x[s:s + C.win]

    def random_window(r):
        x = r["x26"]
        st = F.sliding_starts(len(x), C)
        return x[int(rng.choice(st)):][:C.win]
    pick_f = []
    for ds_ in ("WEDA", "SFMM"):
        cand = [r for r in falls if r["dataset"] == ds_]
        rng.shuffle(cand)
        for r in cand:
            w = impact_window(r); f, p = feat_prob(w)
            if ok_margin(p):
                pick_f.append((w, f, p, r["trial_id"]))
            if sum(1 for q in pick_f if q[3].startswith(ds_[0])) >= 3:
                break
    pick_a = []
    for pool_, need in ((hard, 2), (adl, 4)):
        idx = rng.permutation(len(pool_)); got = 0
        for i in idx:
            r = pool_[i]; w = random_window(r); f, p = feat_prob(w)
            if ok_margin(p) and len(w) == C.win:
                pick_a.append((w, f, p, r["trial_id"])); got += 1
            if got >= need:
                break
    wins = pick_f + pick_a
    assert len(wins) == 12, len(wins)

    # stillness segments: 3 clearly still, 3 clearly not (incl. one with small std but off-1g mean if available)
    def seg_candidates():
        out = []
        for r in pool:
            x = r["x26"].astype(np.float64); mg = F.mag(x)
            for s in range(0, len(mg) - C.confirm + 1, C.confirm // 2):
                seg = mg[s:s + C.confirm]
                out.append((r["trial_id"], seg.astype(np.float32)))
        return out
    cands = seg_candidates()
    rng.shuffle(cands)
    still_l, moving_l = [], []
    for tid, seg in cands:
        sd = float(seg.astype(np.float64).std()); mu = float(seg.astype(np.float64).mean())
        clear_still = sd < 0.6 * std and abs(mu - 1) < 0.5 * tol
        clear_move = sd > 1.6 * std
        if clear_still and len(still_l) < 3:
            still_l.append((tid, seg, 1))
        elif clear_move and len(moving_l) < 3:
            moving_l.append((tid, seg, 0))
        if len(still_l) == 3 and len(moving_l) == 3:
            break
    segs = still_l + moving_l
    assert len(segs) == 6, (len(still_l), len(moving_l))

    t = ["#ifndef TEST_WINDOWS_H", "#define TEST_WINDOWS_H", "",
         "/* 12 real windows + 6 stillness segments from the TRAIN pool (WEDA-FALL / SmartFallMM Meta_wrist, 26 Hz, in g), with expected",
         " * features / probability / decisions computed in Python (float64) from exactly these float32 inputs. Generated by export_final.py. */",
         '#include "fall_model.h"', "",
         "typedef struct { float xyz[WIN_SAMPLES][3]; float feat[N_FEATURES]; float prob; int trigger; } TestWindow;",
         "typedef struct { float mag[CONFIRM_SAMPLES]; int is_still; } StillSeg;", "",
         "static const TestWindow test_windows[] = {"]
    for w, f, p, tid in wins:
        t.append(f"  {{ /* {tid} */")
        t.append("    .xyz = {")
        for row in w:
            t.append(f"      {{{flt(row[0])}, {flt(row[1])}, {flt(row[2])}}},")
        t.append("    },")
        t.append("    .feat = {" + ", ".join(flt(v) for v in f) + "},")
        t.append(f"    .prob = {flt(p)},")
        t.append(f"    .trigger = {1 if p >= thr else 0},")
        t.append("  },")
    t.append("};")
    t.append(f"#define N_TEST_WINDOWS {len(wins)}")
    t.append("")
    t.append("static const StillSeg still_segments[] = {")
    for tid, seg, lab in segs:
        t.append(f"  {{ /* {tid} */")
        t.append("    .mag = {" + ", ".join(flt(v) for v in seg) + "},")
        t.append(f"    .is_still = {lab},")
        t.append("  },")
    t.append("};")
    t.append(f"#define N_STILL_SEGMENTS {len(segs)}")
    t.append("")
    t.append("#endif")
    open(os.path.join(INC, "test_windows.h"), "w").write("\n".join(t) + "\n")
    print("wrote test_windows.h:", len(wins), "windows (triggers:", [1 if q[2] >= thr else 0 for q in wins], "),", len(segs), "segments")
    json.dump(dict(op_mode=a.op, thr=thr, std=std, mean_tol=tol, provisional=bool(prov)), open(os.path.join(RES, "exported_operating_point.json"), "w"), indent=1)


if __name__ == "__main__":
    main()
